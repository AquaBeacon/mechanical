"""Derive support blockers from the validated fastener datums; no CAD edits."""
from pathlib import Path
import json,os
from collections import defaultdict
import trimesh

ROOT=Path(__file__).resolve().parents[1]
ASM=ROOT/'assemblies/parent_hand_service'
WORK=ASM/'_work/analysis/retrofit_20261024'
def read(p):return json.loads(p.read_text(encoding='utf-8'))
def write(p,d):p.write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

def host(label):
    i=label.rsplit('_',1)[-1]
    if label.startswith(('main_pcb_','shelf_joint_')):return 'main_service_frame'
    if label.startswith('pwr_'):return 'power_adapter'
    if label.startswith(('cradle_floor_','cradle_service_')):return 'cradle_floor_foot_'+i
    if label.startswith(('gnss_floor_','gnss_top_')):return 'gnss_sony_shared_column' if i=='3' else 'gnss_fixed_column_'+i
    if label.startswith(('sony_floor_','sony_top_')):return 'gnss_sony_shared_column' if i=='2' else 'sony_fixed_column_'+i
    if label.startswith(('steel_','antenna_')):return 'antenna_service_shelf'
    raise ValueError(label)

def main():
    release=read(WORK/'release_record.json');boxes=defaultdict(list)
    for r in release['fasteners']:
        n=host(r['label']);x,y=r['xy'];folder=ROOT/release['exports'][n]['folder']
        mesh=trimesh.load_mesh(folder/(n+'.stl'));lo,hi=mesh.bounds
        radius=2.1 if r['diameter']==3 else 2.7
        boxes[n].append([x-radius,y-radius,float(lo[2]-.2),2*radius,2*radius,float(hi[2]-lo[2]+.4)])
        if r['nut_z'] is not None:
            boxes[n].append([x-8,y-8,r['nut_z']-.3,16,16,(2.4 if r['diameter']==3 else 3.2)+.7])
    pending=[];config=read(ASM/'print_config.json')
    config['modifiers']=[]
    for n,volumes in boxes.items():
        folder=ROOT/release['exports'][n]['folder'];stem=n+'_support_blocker'
        scad=folder/(stem+'.scad')
        text='// Generated by spec/prepare_parent_retrofit_printing.py from validated release fasteners. NOT A PRINTABLE PART.\nunion(){\n'
        for v in volumes:text+='translate('+json.dumps(v[:3])+') cube('+json.dumps(v[3:])+');\n'
        scad.write_text(text+'}\n',encoding='utf-8')
        metadata=read(folder/'manufacturing.json')
        metadata['non_print_files']=sorted(set(metadata.get('non_print_files',[])+[stem]))
        for dep in [ROOT/'spec/prepare_parent_retrofit_printing.py',WORK/'release_record.json']:
            rel=os.path.relpath(dep,folder).replace('\\','/')
            if rel not in metadata.setdefault('source_dependencies',[]):metadata['source_dependencies'].append(rel)
        write(folder/'manufacturing.json',metadata)
        config['modifiers'].append(dict(host=n,source=(folder/(stem+'.stl')).relative_to(ROOT).as_posix()))
        pending.append(dict(host=n,scad=str(scad),out=str(scad.with_suffix('.stl')),boxes=volumes))
    write(ASM/'print_config.json',config)
    write(WORK/'support_blockers.json',pending)
    print(json.dumps(pending))
if __name__=='__main__':main()
