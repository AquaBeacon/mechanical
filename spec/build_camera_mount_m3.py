    src=src.replace('color("SteelBlue") body();','module camera_mount() { body(); }\ncolor("SteelBlue") camera_mount();')
    src=src.replace('front_pad_w=16; front_pad_d=6; front_pad_x=30;','// Front pads replaced by rear-origin case supports.')
