def run(src,dest,*args):
    p=subprocess.run([OSC,'-o',str(dest),*args,str(src)],cwd=ROOT,capture_output=True,text=True,timeout=180)
    logs=OUT/'_work/logs';logs.mkdir(parents=True,exist_ok=True)
    (logs/(dest.name+'.log')).write_text(p.stdout+p.stderr,encoding='utf-8')
    assert p.returncode==0 and 'ERROR' not in p.stderr and 'WARNING' not in p.stderr,p.stderr

