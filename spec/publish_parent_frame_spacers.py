from pathlib import Path
import datetime,hashlib,json,os,shutil,subprocess,sys
import trimesh
R=Path(__file__).resolve().parents[1];ASM=R/'assemblies/parent_hand_service'
W=ASM/'_work/analysis/frame_spacers_20261024'
OSC='C:/Program Files/OpenSCAD/openscad.exe'
