def read(p):return json.loads(p.read_text(encoding='utf-8-sig'))
def write(p,d):p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def run(cmd,purpose,env=None,timeout=180):
    records=read(W/'processes.json') if (W/'processes.json').exists() else []
    p=subprocess.Popen(cmd,cwd=str(R),env=env,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,creationflags=0x08000000)
    rec=dict(pid=p.pid,start_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),owner='parent_frame_spacers_20261024',purpose=purpose,command=cmd)
    records.append(rec);write(W/'processes.json',records)
    try:out,_=p.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        p.terminate();out,_=p.communicate(timeout=10);rec['timeout']=True
        rec['exit_code']=p.returncode;write(W/'processes.json',records);raise
    rec['exit_code']=p.returncode;rec['ended_utc']=datetime.datetime.now(datetime.timezone.utc).isoformat();write(W/'processes.json',records)
    (W/(purpose+'.log')).write_bytes(out)
    assert p.returncode==0,(purpose,out[-2000:])
    return out.decode('utf-8',errors='replace')
def folder(name):
    if name.startswith('cradle_') or name in ['antenna_service_shelf','ann_mb1_coax_ring_service']:return R/'parts/parent/interior/printed/ann_mb1_internal_rack'
    if name.startswith('gnss_'):return R/'parts/parent/interior/printed/gnss_universal_carrier'
    return R/'parts/parent/interior/printed/parent_hand_service'
def update_manufacturing():
    from collections import Counter
    path=ASM/'manufacturing_parts.json';d=read(path)
    previous=W/'history/manufacturing_parts.json'
    if not previous.exists():shutil.copyfile(path,previous)
    rows=read(ASM/'placement.json')['items']
    parts=read(W/'publication.json')['exports']
    d['printed_parts']=list(parts)
    d['purchased_fasteners_by_file']=dict(Counter(r.get('file',Path(r['part']).name) for r in rows if r['part'].endswith('/screw')))
    d['metal_fasteners']=d['purchased_fasteners_by_file'].copy()
    d['revision']='2026-10-24 flat MAIN frame; independent 3.5mm clearance spacers'
    d['spacer_delivery']=dict(revision=d['revision'],mode='individual',axes=12,quantities={n:1 for n in parts if n.startswith(('cradle_floor_foot_','gnss_fixed_','gnss_sony_shared_','sony_fixed_'))})
    write(path,d)
def refresh_shared_blocker(hardware):
    host=folder('gnss_sony_shared_column');stem='gnss_sony_shared_column_support_blocker'
    row=next(r for r in hardware if r['label']=='sony_top_2')
    x,y=row['xy'];z=row['nut_z'];marker='// Side-entry Sony nut pocket, frame/spacer revision.'
    source=host/(stem+'.scad');base=source.read_text(encoding='utf-8').split(marker)[0].rstrip()
    source.write_text(base+'\n'+marker+'\ntranslate('+json.dumps([x-4,y-4,z-.3])+') cube([8,12,3.3]);\n',encoding='utf-8')
    run([OSC,'-o',str(host/(stem+'.stl')),str(source)],'render_shared_blocker')
    return dict(origin_mm=[x-4,y-4,z-.3],size_mm=[8,12,3.3],axis_mm=[x,y])
def main():
    job=read(W/'build_run.json');native=Path(job['run_dir']);assert read(native/'report.json')['status']=='passed'
    report=json.loads(next(line.split('=',1)[1] for line in (native/'logs/freecad.log').read_text(encoding='utf-8').splitlines() if line.startswith('FRAME_SPACER_REPORT=')))
    assert report['passed']
    for rel,s in read(native/'job.json')['snapshots'].items():
        current=sha(R/rel)
        # Resume an interrupted publication only for exact verified exports.
        exported=native/Path(rel).name
        resumed=rel.endswith('.step') and exported.is_file() and current==sha(exported)
        assert current==s['sha256'] or resumed,rel
    # Snapshot the preceding review files before replacing the active outputs.
    history=W/'history';history.mkdir(exist_ok=True)
    for file in ['placement.json','service_placement.json','print_config.json']:
        if not (history/file).exists():shutil.copyfile(ASM/file,history/file)
    exports={}
    for name in report['parts']:
        dst=folder(name);mesh=trimesh.load_mesh(native/(name+'.stl'))
        for suffix in ['scad','step','stl']:
            previous=history/(name+'.'+suffix)
            if not previous.exists():shutil.copyfile(dst/(name+'.'+suffix),previous)
        assert mesh.is_watertight and mesh.is_winding_consistent and mesh.volume>0
        scad='// Generated by spec/build_parent_hand_service.py --service-retrofit; edit scad/lib/parent_service_retrofit.py.\n'
        scad+='polyhedron(points='+json.dumps(mesh.vertices.tolist())+',faces='+json.dumps(mesh.faces[:,::-1].tolist())+',convexity=10);\n'
        (dst/(name+'.scad')).write_text(scad,encoding='utf-8')
        for suffix in ['step','stl']:shutil.copyfile(native/(name+'.'+suffix),dst/(name+'.'+suffix))
        independent=W/(name+'_render.stl')
        log=run([OSC,'-o',str(independent),str(dst/(name+'.scad'))],'render_'+name)
        assert 'WARNING:' not in log and 'ERROR:' not in log,log
        check=trimesh.load_mesh(independent);assert check.is_watertight and check.is_winding_consistent
        assert abs(check.volume-mesh.volume)/mesh.volume<.001
        exports[name]=dict(folder=dst.relative_to(R).as_posix(),sha256=sha(dst/(name+'.stl')),volume_mm3=mesh.volume,bounds_mm=mesh.bounds.tolist())
    # New purchased screw variant uses the existing parametric SCAD and converter.
    screws=R/'parts/common/interior/cots/screw';inter=screws/'_work/intermediate';inter.mkdir(parents=True,exist_ok=True)
    defs=['-D','d=3','-D','l=65','-D','head_d=5.5','-D','head_h=3']
    for suffix,dest in [('stl',screws/'screw_m3x65.stl'),('csg',inter/'screw_m3x65.csg')]:
        run([OSC,*defs,'-o',str(dest),str(screws/'screw.scad')],'screw65_'+suffix)
    env=os.environ.copy();env.update(CSG_IN=str(inter/'screw_m3x65.csg'),STEP_OUT=str(screws/'screw_m3x65.step'),STL_REF=str(screws/'screw_m3x65.stl'),OPENSCAD=OSC)
    run([FC,str(R/'scad/lib/csg_to_step.py')],'screw65_step',env)
    for file in ['placement.json','service_placement.json']:
        d=read(ASM/file)
        prefixes=['retrofit_'+p for p in ['cradle_floor_','cradle_service_','gnss_floor_','gnss_top_','sony_floor_','sony_top_']]
        d['items']=[row for row in d['items'] if not any(row['label'].startswith(p) for p in prefixes)]
        for row in report['fasteners']:
            label=row['label'];x,y=row['xy']
            if file.startswith('service') and label.startswith('cradle_'):continue
            d['items'].append(dict(label='retrofit_'+label+'_bolt',part='parts/common/interior/cots/screw',file='screw_m3x'+str(row['length']),group='interior',color='Silver',ops=[{'translate':[x,y,row['head_z']]}]))
            d['items'].append(dict(label='retrofit_'+label+'_nut',part='parts/common/interior/cots/screw',file='screw_nut_m3',group='interior',color='Silver',ops=[{'translate':[x,y,row['nut_z']]},{'rotate':[0,0,30]}]))
            if row['washer']:d['items'].append(dict(label='retrofit_'+label+'_washer',part='parts/common/interior/cots/screw',file='screw_washer_m3_05',group='interior',color='Silver',ops=[{'translate':[x,y,8.34]}]))
        d['build_order']=[row['label'] for row in d['items']]
        d['frame_spacer_revision']=dict(date='2026-10-24',clearance_d_mm=3.5,standalone_axes=12,pcb_pilot_d_mm=2.8,maximum_screw_length_mm=65)
        d['retrofit'].update(maximum_new_screw_length_mm=65,spacer_fastening='3.5mm clearance, M3 through bolts and underside nuts; shared Sony axis uses side-entry captured nut',service='Remove interior from case, hold underside nuts, remove four M3x30 frame bolts; short feet become loose. Service pose is a review configuration, not a certified removal sequence.')
        if file=='placement.json':d['note']='Flat-bottom MAIN frame; standalone clearance spacers. See frame_spacer_printability_report.md.'
        write(ASM/file,d)
    note='MAIN枠下面を脚と同じ高さへ修正。独立スペーサ12軸は対辺3.5 mmの通し穴。一体ねじ座は2.8 mm下穴の直接締結を維持。独立スペーサはM3通しねじとナットで固定。部品数16種類16個。詳しくは ../frame_spacer_printability_report.md。'
    config=read(ASM/'print_config.json');config['note']=note
    config['notes']=list(dict.fromkeys(config.get('notes',[])+['assemblies/parent_hand_service/frame_spacer_printability_report.md']))
    # Exclude inaccessible support inside the new shared-column nut pocket.
    refresh_shared_blocker(report['fasteners'])
    write(ASM/'print_config.json',config)
    for dst in sorted({folder(n) for n in report['parts']}):
        meta=read(dst/'manufacturing.json')
        for dep in ['scad/lib/parent_service_retrofit.py','spec/build_parent_frame_spacers.py','spec/revise_parent_printability.py']:
            rel=os.path.relpath(R/dep,dst).replace('\\','/')
            if rel not in meta['source_dependencies']:meta['source_dependencies'].append(rel)
        write(dst/'manufacturing.json',meta)
    # Publish fresh native STL bytes after every generated SCAD/modifier sibling.
    for name in report['parts']:shutil.copyfile(native/(name+'.stl'),folder(name)/(name+'.stl'))
    write(W/'geometry_checks.json',report)
    write(W/'publication.json',dict(exports=exports,hardware=report['fasteners'],build_run=job))
    update_manufacturing()
    print('Published12 revised parts and updated hardware; sync/slice/assembly verification next.',flush=True)
if __name__=='__main__':main()
