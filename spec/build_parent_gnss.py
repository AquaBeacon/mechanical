def finish(s,amount,selector=None):
    s=s.removeSplitter()
    edges=sharp_edges(s)
    if selector is not None:edges=[e for e in edges if selector(e)]
    (P/'_work/intermediate').mkdir(parents=True,exist_ok=True)
    s.exportStep(str(P/'_work/intermediate/rack_unfinished.step'))
    result=None
    for size in [amount,.2,.1,.05,.025]:
        try:
            candidate=s.makeChamfer(size,edges)
            if not candidate.isValid() or len(candidate.Solids)!=1:continue
            result=candidate;finish.last_amount=size;print('Edge finish',size,len(edges),flush=True);break
        except Part.OCCError:pass
    assert result is not None, 'Edge finishing failed'
    assert result.isValid() and len(result.Solids)==1
    return result
def save(folder,name,s,scad=False):
    folder.mkdir(parents=True,exist_ok=True)
    assert s.isValid(),name
    s.exportStep(str(folder/(name+'.step')))
    mesh=MeshPart.meshFromShape(Shape=s,LinearDeflection=.025,AngularDeflection=.10,Relative=False)
    mesh.write(str(folder/(name+'.stl')))
    if scad:
        points,faces=mesh.Topology
        txt='// Generated by spec/build_parent_gnss.py; dimensions and edge finishing are parametric there.\n'
        # OpenSCAD polyhedron faces use clockwise order viewed from outside;
        # OCCT mesh topology uses the opposite convention.
        txt+='polyhedron(points='+json.dumps([[p.x,p.y,p.z] for p in points])+',faces='+json.dumps([list(reversed(f)) for f in faces])+',convexity=10);\n'
        (folder/(name+'.scad')).write_text(txt,encoding='utf-8')

