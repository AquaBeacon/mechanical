"""Build integral side fixtures and update only accessory rows in placement.json.

SCAD owns geometry. Existing frame and quick-release mesh bytes are retained.
Run this after prepare_child_horizontal_plate_frame.py to restore the accessory
installation. Placement.side_twist_mount owns station selection and light count.
"""
from pathlib import Path
import argparse, ast, hashlib, json, re
import numpy as np
import trimesh
from prepare_child_horizontal_plate_frame import ROOT, OUT, OSC, call, save, matrix, printed_baseline
from build_quick_release_prototypes import hardware

PART=ROOT/'parts/child/exterior/printed/child_horizontal_twist_mount'
QR='parts/common/jigs/quick_release_prototypes'
LIGHT='parts/child/exterior/printed/child_simple_light_mount'
SCREW='parts/common/interior/cots/screw'
TAG='side_twist_accessory'
SHARED=ROOT/'scad/lib/child_horizontal_twist_interface.scad'
HARDWARE='parts/common/interior/cots/quick_release_hardware'

def screw_recipe(suffix):
    """Use the established COTS variant table instead of a second definition."""
    line=next(line for line in (ROOT/SCREW/'variants.txt').read_text(encoding='utf-8').splitlines()
              if line.split() and line.split()[0]==suffix)
    return line.split()[1:]

def verify_trials():
    """Re-render unchanged branches after adding a male mounting variant."""
    import os
    from scipy.spatial import cKDTree
    from concurrent.futures import ThreadPoolExecutor
    from build_quick_release_prototypes import KINDS
    work=ROOT/QR/'_work/intermediate/mount_variant_equivalence';work.mkdir(parents=True,exist_ok=True)
    def one(kind):
        original=ROOT/QR/f'quick_release_prototypes_{kind}.stl';candidate=work/(kind+'.stl')
        call([OSC,'--export-format','asciistl','-D',f'part="{kind}"','-o',candidate,ROOT/QR/'quick_release_prototypes.scad'],
             ROOT/QR/f'_work/logs/mount_equivalence_{kind}.log')
        a=trimesh.load(original,force='mesh');b=trimesh.load(candidate,force='mesh')
        error=max(float(cKDTree(x.vertices).query(y.vertices)[0].max()) for x,y in ((a,b),(b,a)))
        data=dict(kind=kind,vertex_error_mm=error,bounds_error_mm=float(np.max(np.abs(a.bounds-b.bounds))),
            volume_error_mm3=abs(float(a.volume-b.volume)),original_sha256=hashlib.sha256(original.read_bytes()).hexdigest(),
            candidate_watertight=bool(b.is_volume))
        if error>.0001 or data['volume_error_mm3']>.1 or not b.is_volume:raise RuntimeError(str(data))
        # Retain mesh bytes only after proving the current source still describes it.
        os.utime(original,None);return data
    with ThreadPoolExecutor(max_workers=2) as pool:reports=list(pool.map(one,KINDS))
    save(ROOT/QR/'_work/analysis/mount_variant_equivalence/validation.json',dict(result='PASS',parts=reports))
    print('Unchanged trial variants verified:',len(reports),flush=True)

def generate_interface():
    q=hardware()
    source=(ROOT/QR/'quick_release_prototypes.scad').read_text(encoding='utf-8')
    for name in ('pad','pad_t','plate_corner_r','twist_plate_t','twist_knob_d','post_d','post_h'):
        q[name]=float(re.search(rf'(?m)^\s*{name}\s*=\s*([0-9.]+)\s*;',source).group(1))
    q['mount_cs_depth']=float(re.search(r'module twist_male_mount\(\)[\s\S]*?twist_plate_t-([0-9.]+)',source).group(1))
    text='// Generated by tools/build_child_horizontal_accessories.py; do not edit.\n'
    text+='// Dimensions copied mechanically from the canonical, unchanged C-twist source.\n'
    for name in ('pad','pad_t','plate_corner_r','mount_pitch','mount_d','twist_plate_t','ring_h','twist_axis_z','turn_deg','twist_lock_gap','twist_knob_d'):
        text+=f'qr_{name} = {q[name]:.12g};\n'
    text+='qr_locked_height = qr_pad_t+qr_ring_h+qr_twist_plate_t+qr_twist_lock_gap;\n'
    light=(ROOT/LIGHT/'child_simple_light_mount.scad').read_text(encoding='utf-8')
    for name in ('holder_id','holder_length','wall','plate_t','service_gap','ear_width','ear_height','ear_t','ear_end_margin','split_gap'):
        value=float(re.search(rf'(?m)^lm_{name}\s*=\s*([0-9.]+)',light).group(1))
        text+=f'chlm_{name} = {value:.12g};\n'
    if not SHARED.exists() or SHARED.read_text(encoding='utf-8')!=text:
        SHARED.write_text(text,encoding='utf-8')
    return q

def build():
    generate_interface(); reports={}; interface=None
    for variant in ('frame_receiver','light_twist'):
        stem='child_horizontal_twist_mount_'+variant
        result=call([OSC,'--export-format','asciistl','-D',f'part="{variant}"','-o',PART/(stem+'.stl'),
                     PART/'child_horizontal_twist_mount.scad'],PART/f'_work/logs/{variant}.log')
        line=next(l.split('ECHO: ',1)[1] for l in result.splitlines() if 'ECHO: ["SIDE_TWIST_R4"' in l)
        interface=ast.literal_eval(line)
        from clean_stl_degenerates import clean
        cleanup=clean(PART/(stem+'.stl'),PART/f'_work/analysis/geometry/{variant}_edge_flip.json',binary=False)
        mesh=trimesh.load(PART/(stem+'.stl'),force='mesh')
        if not mesh.is_volume or len(mesh.split())!=1: raise RuntimeError(f'Invalid solid {stem}')
        reports[stem]=dict(bounds_mm=mesh.bounds.tolist(),volume_mm3=float(mesh.volume),watertight=True,
                           connected_components=1,degenerate_triangles=int(np.count_nonzero(mesh.area_faces<1e-12)),
                           numerical_cleanup=cleanup,sha256=hashlib.sha256((PART/(stem+'.stl')).read_bytes()).hexdigest())
    save(PART/'_work/analysis/geometry/validation.json',dict(result='PASS',parts=reports))
    save(PART/'_work/analysis/geometry/interface.json',interface)
    for variant in ('lock_bolt','lock_nut','lock_washer','rubber_pads'):
        folder=ROOT/HARDWARE
        call([OSC,'--export-format','asciistl','-D',f'part="{variant}"','-o',folder/f'quick_release_hardware_{variant}.stl',
              folder/'quick_release_hardware.scad'],folder/f'_work/logs/{variant}.log')
    return interface

def install(placement, interface):
    """Idempotent: keep all unrelated placement rows and station choices."""
    q=generate_interface()
    (_,fw,fh,fp,plate_t,rn,ru,rv,angle,shift,centre_n,bore,length)=interface
    settings=placement.setdefault('side_twist_mount',dict(
        specification='docs/child_horizontal_twist_interface.md',revision=4,
        light_station='right_front',light_axis='up',reference_holder_id_mm=33,
        reference_holder_length_mm=81,user_confirmed_date='2026-10-11'))
    if settings['light_axis']!='up': raise ValueError('Only confirmed upward holder installation implemented')
    a=placement['attachment_interface']; col=sorted(set(z for y,z in a['hole_centres_yz_mm'] if z not in (16,220)))
    centres=sorted(set(y for y,z in a['hole_centres_yz_mm'] if z==col[0]))
    z=(col[0]+col[-1])/2
    stations={f'{side}_{end}':dict(origin_mm=[a['side_faces_x_mm'][i],y,z],
              rotation_deg=[90,0,90] if side=='right' else [90,0,-90],
              status='reserved') for i,side in enumerate(('left','right'))
              for y,end in zip(centres,('rear','front'))}
    key=settings['light_station']
    if key!='right_front':raise ValueError('Rev.4 integral geometry is verified only for right_front; adapt and verify its outward station offset first')
    st=stations[key]; st['status']='light_installed'
    settings['revision']=4
    settings['stations']=stations; settings['dock_rotation_deg']=angle
    settings['dock_offset_uvn_mm']=[ru,rv,rn]
    settings['locked_light_axis_xyz']=[0,0,1]
    settings['lock_knob_axis_xyz']=(matrix([{'translate':st['origin_mm']},{'rotate':st['rotation_deg']},
        {'rotate':[0,0,angle]}])[:3,0]).round(12).tolist()
    settings['lock_knob_side']='front_of_light, horizontal +Y'
    settings['hand_clearance_bounds_mm']={'min_y':-45,'max_y':45,'min_z':40,'max_z':210}
    settings['light_centre_xyz_mm']=(matrix([{'translate':st['origin_mm']},{'rotate':st['rotation_deg']}])@np.array([ru,rv,rn+centre_n,1]))[:3].tolist()
    # Preserve unrelated rows, including all already-printed stock and fixtures.
    placement['items']=[r for r in placement['items'] if r.get('owner')!=TAG]
    placement['fastener_joints']=[r for r in placement['fastener_joints'] if r.get('owner')!=TAG]
    placement.setdefault('groups',{}).setdefault('accessories',True)
    ops=[{'translate':st['origin_mm']},{'rotate':st['rotation_deg']}]
    transform=matrix(ops)
    def row(label,folder,stem,extra,color='Silver',printed=False):
        r=dict(label='side_light_'+label,part=folder,file=stem,group='accessories' if printed else 'fasteners',
               ops=ops+extra,color=color,print=printed,owner=TAG)
        placement['items'].append(r); return r
    row('frame_receiver',PART.relative_to(ROOT).as_posix(),'child_horizontal_twist_mount_frame_receiver',[],
        'SteelBlue',True)
    dock=[{'translate':[ru,rv,rn]},{'rotate':[0,0,angle]}]
    row('light_twist',PART.relative_to(ROOT).as_posix(),'child_horizontal_twist_mount_light_twist',[
        {'translate':[ru,rv,rn]}],'Orange',True)
    row('twist_knob',QR,'quick_release_prototypes_twist_knob',dock+[
        {'translate':[q['twist_face_x']+q['washer_t'],0,q['twist_axis_z']]},{'rotate':[0,90,0]}], 'SeaGreen',True)
    for kind in ('lock_bolt','lock_nut','lock_washer','rubber_pads'):
        r=row(kind,HARDWARE,'quick_release_hardware_'+kind,dock)
        if kind=='rubber_pads':r['group']='accessories';r['color']='DimGray'
    holder=[{'translate':[ru,rv,rn+shift]},{'rotate':[90,0,180]}]
    row('holder_cap',LIGHT,'child_simple_light_mount_cap',holder,'SteelBlue',True)
    # Hardware helper in mounting-face coordinates. All nuts except the two
    # retained side-frame seats are accessible ordinary nuts with washers.
    def joint(name,uv,head,rotation,length,nut,nut_rotation,other_ops=None,nut_washer=True,flat=False,head_washer=True):
        base=other_ops or []; prefix='side_light_'+name
        seat=[uv[0],uv[1],head]; npos=[uv[0],uv[1],nut]
        screw_ops=base+[{'translate':seat},{'rotate':rotation}]
        row(name+'_screw',SCREW,f'screw_m3x{length}'+('_flat' if flat else ''),screw_ops)
        if head_washer: row(name+'_head_washer',SCREW,'screw_washer_m3_05',screw_ops+[{'translate':[0,0,-0.5]}])
        nops=base+[{'translate':npos},{'rotate':nut_rotation}]
        row(name+'_nut',SCREW,'screw_nut_m3',nops+[{'rotate':[0,0,0 if name.startswith('frame_') else 30]}])
        if nut_washer: row(name+'_nut_washer',SCREW,'screw_washer_m3_05',nops+[{'translate':[0,0,-0.5]}])
        tm=transform@matrix(base); hm=tm@matrix([{'translate':seat},{'rotate':rotation}]); nm=tm@matrix(nops)
        # ZYZ-independent xyz angles from the full proper rotation, as used by
        # the established frame checker (trimesh transformations convention).
        hr=np.degrees(trimesh.transformations.euler_from_matrix(hm)).tolist()
        nr=np.degrees(trimesh.transformations.euler_from_matrix(nm)).tolist()
        placement['fastener_joints'].append(dict(label=prefix,seat_mm=hm[:3,3].tolist(),axis_rotation_deg=hr,
            length_mm=length,nut_start_mm=nm[:3,3].tolist(),nut_rotation_deg=nr,nominal_diameter_mm=3,
            exposed_nut=nut_washer,owner=TAG))
    for i,v in enumerate((-fp/2,fp/2)):
        joint('frame_'+str(i),[0,v],plate_t+.5,[0,0,0],18,
              -placement['dimensions_mm']['side_thickness']+.4,[0,0,0],nut_washer=False)
    # Holder clamp joints reuse its source dimensions (axes along native +Y).
    light_source=(ROOT/LIGHT/'child_simple_light_mount.scad').read_text(encoding='utf-8')
    scalar=lambda n:float(re.search(rf'(?m)^\s*{n}\s*=\s*([0-9.]+)\s*;',light_source).group(1))
    ro=scalar('lm_holder_id')/2+scalar('lm_wall'); cy=scalar('lm_plate_t')+scalar('lm_service_gap')+ro
    ex=ro+scalar('lm_ear_width')/2-1; ez=scalar('lm_holder_length')/2-scalar('lm_ear_height')/2-scalar('lm_ear_end_margin')
    index=0
    for x in (-ex,ex):
        for zz in (-ez,ez):
            # Re-express source X/Z/Y as U/V/N for the helper; preserves up axis.
            joint('clamp_'+str(index),[ru-x,rv+zz],rn+shift+cy+.75+6+.5,[0,0,0],20,
                  rn+shift+cy-.75-6-.5,[180,0,0]);index+=1
    # The lock requires a real M3x40 HEX head retained by the existing knob.
    # COTS screw_m3x40 is a pan-head proxy; use the canonical QR metal modules.
    stock=set(placement['print_progress']['source_mesh_sha256'])
    remaining=[r for r in placement['items'] if r['print'] and r['part']+'/'+r['file']+'.stl' not in stock]
    placement['print_progress']['base_remaining_instances']=sum(r.get('owner')!=TAG for r in remaining)
    placement['print_progress']['remaining_instances']=len(remaining)
    placement['print_progress']['already_printed_instances']=sum(r['print'] for r in placement['items'])-len(remaining)
    return settings

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--placement-only',action='store_true');parser.add_argument('--verify-trials',action='store_true');parser.add_argument('--rebuild-frame',action='store_true');parser.add_argument('--reuse-interfaces',action='store_true');args=parser.parse_args()
    previous=json.loads((OUT/'placement.json').read_text(encoding='utf-8')).get('side_twist_mount')
    previous_config=json.loads((OUT/'print_config.json').read_text(encoding='utf-8'))
    if args.rebuild_frame:
        import sys
        call([sys.executable,ROOT/'tools/prepare_child_horizontal_plate_frame.py']+
             (['--reuse-interfaces'] if args.reuse_interfaces else []),OUT/'_work/logs/accessory_frame_rebuild.log')
    if args.verify_trials:verify_trials()
    interface=json.loads((PART/'_work/analysis/geometry/interface.json').read_text()) if args.placement_only else build()
    placement=json.loads((OUT/'placement.json').read_text(encoding='utf-8'))
    if previous is not None:placement['side_twist_mount']=previous
    install(placement,interface);save(OUT/'placement.json',placement);printed_baseline()
    if args.rebuild_frame:save(OUT/'print_config.json',previous_config)
    call(['python',ROOT/'scad/lib/asm_gen.py',OUT/'placement.json',OUT/'child_horizontal_plate_frame_view.scad'],
         OUT/'_work/logs/view_generation.log')
    print(json.dumps(dict(result='BUILT',light_station=placement['side_twist_mount']['light_station'],
        accessory_print_parts=4,dock_rotation_deg=interface[8])))

if __name__=='__main__':main()
