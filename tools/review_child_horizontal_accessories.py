"""Regenerate whole assembly and side-light views from placement.json."""
import hashlib,json,os
import numpy as np
import trimesh
from prepare_child_horizontal_plate_frame import ROOT,OUT,OSC,load_world,call,save,matrix
from build_child_horizontal_accessories import TAG

def light_review_source(placement,entries,source):
    """Generated two-pose view; placement.json remains the only placement source."""
    from build_quick_release_prototypes import hardware
    q=hardware();settings=placement['side_twist_mount'];station=settings['stations'][settings['light_station']]
    dock=matrix([{'translate':station['origin_mm']},{'rotate':station['rotation_deg']},
        {'translate':settings['dock_offset_uvn_mm']},{'rotate':[0,0,settings['dock_rotation_deg']]}])
    lines=['// Generated by tools/review_child_horizontal_accessories.py from placement.json.',
        '// pose=locked: upright light and horizontal side knob; entry: bolt removed, light tilted.',
        'pose="locked"; // [locked,entry]', 'show_frame=true;', '/* [Hidden] */',
        f'light_angle=pose=="entry" ? {-q["turn_deg"]:g} : 0;',
        f'cam_lift=-light_angle/{q["turn_deg"]:g}*{q["twist_cam_lift"]:g};',
        f'module light_motion() {{ multmatrix({json.dumps(dock.tolist())}) translate([0,0,cam_lift]) rotate([0,0,light_angle]) multmatrix({json.dumps(np.linalg.inv(dock).tolist())}) children(); }}']
    for r,m in entries:
        ops=' '.join(f'{k}({json.dumps(v)})' for op in r.get('ops',[]) for k,v in op.items())
        target=ROOT/r['part']/(r['file']+'.stl');relative=os.path.relpath(target,source.parent).replace('\\','/')
        prefix=''
        if r.get('owner')!=TAG:prefix='if(show_frame) '
        elif r['label'] in ('side_light_twist_knob','side_light_lock_bolt','side_light_lock_washer'):
            prefix='if(pose=="locked") '
        elif r['label'] in ('side_light_light_twist','side_light_holder_cap','side_light_rubber_pads') or r['label'].startswith('side_light_clamp_'):
            prefix='light_motion() '
        lines.append(prefix+f'color({json.dumps(r["color"])}) {ops} import({json.dumps(relative)});')
    source.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    return dock

def main():
    p=json.loads((OUT/'placement.json').read_text(encoding='utf-8'));world=load_world(p)
    selected=[(r,m) for r,m in world if r.get('owner')==TAG or r['label'] in ('right_side_frame','right_front_guard')]
    out=OUT/'child_horizontal_plate_frame.stl';trimesh.util.concatenate([m for r,m in world]).export(out)
    save(OUT/'_work/analysis/layout/assembly_stl.json',dict(purpose='assembly view only; print portable parts',items=len(world),
        placement_sha256=hashlib.sha256((OUT/'placement.json').read_bytes()).hexdigest(),output_sha256=hashlib.sha256(out.read_bytes()).hexdigest()))
    call(['python',ROOT/'scad/lib/asm_gen.py',OUT/'placement.json',OUT/'child_horizontal_plate_frame_view.scad'],OUT/'_work/logs/view_generation.log')
    colors={'frame':'#407a91','clamp':'#818d94','vessel':'#9fb9c3','ballast':'#414d55','ballast_cap':'#c99452','accessories':'#4f9d8b','fasteners':'#aeb4ba'}
    images=OUT/'_work/images';images.mkdir(parents=True,exist_ok=True)
    focused=OUT/'child_horizontal_plate_frame_light_view.scad'
    dock=light_review_source(p,selected,focused)
    for pose in ('locked','entry'):
        call([OSC,'-D',f'pose="{pose}"','-D','show_frame=false','--imgsize=1400,1100','--projection=o',
              '--viewall','--autocenter','--camera=450,160,210,151,80,130','-o',images/f'side_twist_{pose}.png',focused],
             OUT/f'_work/logs/side_twist_{pose}.log')
    # Test the canonical SCAD itself, including all group declarations/imports.
    call([OSC,'--imgsize=1400,1100','--projection=o','--viewall','--autocenter',
          '--camera=600,470,420,30,0,115','-o',images/'child_horizontal_plate_frame_scad.png',
          OUT/'child_horizontal_plate_frame_view.scad'],OUT/'_work/logs/scad_full_view.log')
    for name,entries,camera,exploded in (
        ('side_twist_light',selected,'450,380,330,155,55,130',False),
        ('side_twist_exploded',[(r,m) for r,m in selected if r['print']],'620,400,310,205,55,130',True),
        ('side_twist_complete',world,'600,470,420,30,0,115',False)):
        lines=['// Generated from ../../placement.json; do not edit.']
        for r,m in entries:
            color=colors[r['group']]
            if r['label']=='side_light_light_twist':color='#ce9350'
            if r['label']=='side_light_twist_knob':color='#71a83f'
            if 'holder_cap' in r['label']:color='#a5c9bd'
            if r['group']=='vessel':color=[.6,.75,.8,.35]
            ops=' '.join(f'{k}({json.dumps(v)})' for op in r.get('ops',[]) for k,v in op.items())
            if exploded:
                d={'side_light_light_twist':60,'side_light_holder_cap':100,'side_light_twist_knob':30}.get(r['label'],0)
                ops=f'translate([{d},0,0]) '+ops
            lines.append(f'color({json.dumps(color)}) {ops} import({json.dumps((ROOT/r["part"]/(r["file"]+".stl")).as_posix())});')
        source=OUT/f'_work/intermediate/{name}.scad';source.parent.mkdir(parents=True,exist_ok=True)
        source.write_text('\n'.join(lines)+'\n',encoding='utf-8')
        call([OSC,'--imgsize=1400,1100','--projection=o','--viewall','--autocenter','--camera='+camera,
              '-o',images/(name+'.png'),source],OUT/f'_work/logs/{name}.log')
    # Print pose/edge and hole-roof sections are actual rendered STL profiles.
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams['font.family']='Yu Gothic'
    fig,axes=plt.subplots(1,3,figsize=(15,5),facecolor='#f4f3ef')
    for ax,(label,normal,origin,title,coords) in zip(axes,(
        ('side_light_frame_receiver',[1,0,0],[20,0,0],'一体型メス・フレーム台座断面', [1,2]),
        ('side_light_light_twist',[1,0,0],[0,0,0],'一体型オス・ホルダー断面',[1,2]),
        ('side_light_holder_cap',[1,0,0],[26,0,0],'既存押さえ・ねじ穴断面',[1,2]))):
        r=next(r for r,m in world if r['label']==label);mesh=trimesh.load(ROOT/r['part']/(r['file']+'.stl'),force='mesh')
        section=mesh.section(plane_origin=origin,plane_normal=normal)
        for loop in section.discrete:ax.plot(loop[:,coords[0]],loop[:,coords[1]],color='#407a91',linewidth=1.2)
        ax.set_title(title);ax.set_aspect('equal');ax.grid(alpha=.15)
    fig.tight_layout();fig.savefig(images/'side_twist_sections.png',dpi=140);plt.close(fig)

    from matplotlib.collections import PolyCollection
    from matplotlib.patches import Rectangle
    from build_quick_release_prototypes import hardware
    q=hardware();fig,axes=plt.subplots(1,2,figsize=(12,6),facecolor='#f4f3ef')
    optical=np.array(p['side_twist_mount']['light_centre_xyz_mm']);upright=np.array([0.,0.,1.])
    for ax,angle,title in zip(axes,[-q['turn_deg'],0],['差込位置：横ボルトを抜いた状態','固定位置：ライト上向き、ノブは横']):
        motion=dock@matrix([{'translate':[0,0,-angle/q['turn_deg']*q['twist_cam_lift']]},
                           {'rotate':[0,0,angle]}])@np.linalg.inv(dock)
        for r,m in selected:
            if r.get('owner')!=TAG or not r['print']:continue
            if r['label']=='side_light_twist_knob' and angle:continue
            moving=r['label'] in ('side_light_light_twist','side_light_holder_cap')
            viewed=m.copy()
            if moving:viewed.apply_transform(motion)
            ax.add_collection(PolyCollection(viewed.triangles[:,:,[1,2]],facecolors=colors[r['group']] if not moving else '#d09b61',edgecolors='none'))
        axis=motion[:3,:3]@upright;centre=(motion@np.r_[optical,1])[:3]
        start=centre+axis*45;end=centre+axis*65
        ax.annotate('',xy=end[[1,2]],xytext=start[[1,2]],arrowprops=dict(arrowstyle='->',color='#438562',lw=2))
        if not angle:
            ax.text(114,130,'手回しノブ',ha='left',va='center',fontsize=10,color='#367652')
        ax.set_xlim(15,155);ax.set_ylim(75,205);ax.set_aspect('equal');ax.set_title(title);ax.set_xlabel('Y / mm');ax.set_ylabel('Z / mm');ax.grid(alpha=.15)
    fig.suptitle('差し込んで反時計回り60° → 上向きで停止 → 横のノブを締める',fontsize=13)
    fig.tight_layout();fig.savefig(images/'side_twist_locked_entry.png',dpi=150);plt.close(fig)
    fig,axes=plt.subplots(1,2,figsize=(13,6),facecolor='#f4f3ef')
    for ax,coords,title in ((axes[0],[1,2],'側面：中央の手の通路'),(axes[1],[1,0],'上面：突出を縮小')):
        for r,m in selected:
            if not r['print']:continue
            color='#407a91' if r.get('owner')!=TAG else '#65a994'
            ax.add_collection(PolyCollection(m.triangles[:,:,coords],facecolors=color,edgecolors='none'))
        ax.autoscale();ax.set_aspect('equal');ax.set_title(title);ax.set_xlabel('Y / mm');ax.grid(alpha=.15)
    axes[0].add_patch(Rectangle((-45,40),90,170,facecolor='#b9d9ac',edgecolor='#4c8652',alpha=.28,lw=1.5))
    axes[0].text(0,45,'中央90 mm\n追加部品なし',ha='center',va='bottom',fontsize=10,color='#376c40')
    axes[0].set_ylabel('Z / mm')
    right_face=122
    new_outer=max(m.bounds[1,0] for r,m in selected if r.get('owner')==TAG and r['print'])
    axes[1].plot([-32.5+60,32.5+60,32.5+60,-32.5+60,-32.5+60],[right_face, right_face,245.5,245.5,right_face],'--',color='#bc7865',label='旧Rev.1のホルダー包絡')
    axes[1].plot([47.5,112.5,112.5,47.5,47.5],[right_face,right_face,190.5,190.5,right_face],':',color='#976f39',label='Rev.2：突出68.5 mm')
    axes[1].annotate('',xy=(130,new_outer),xytext=(130,right_face),arrowprops={'arrowstyle':'<->','color':'#376c40'})
    axes[1].text(133,(new_outer+right_face)/2,f'{new_outer-right_face:.1f} mm',va='center',color='#376c40')
    axes[1].set_xlim(-115,165);axes[1].set_ylim(105,253);axes[1].set_ylabel('X / mm');axes[1].legend(loc='upper left',fontsize=9)
    fig.suptitle(f'内側延長・段差なし：突出68.5 → {new_outer-right_face:.1f} mm',fontsize=14)
    fig.tight_layout();fig.savefig(images/'side_twist_comparison.png',dpi=150);plt.close(fig)
    fig,axes=plt.subplots(1,3,figsize=(15,5),facecolor='#f4f3ef')
    labels={'right_side_frame','right_front_guard','right_rear_guard','right_rotation_key','removable_upper_frame'}
    for ax,height,title in zip(axes,[100,131.5,205.8],['追加フレーム：側板の内側','回転止めの逃げ','上部フレームの逃げ']):
        for r,m in world:
            if r['label'] not in labels:continue
            section=m.section(plane_origin=[0,0,height],plane_normal=[0,0,1])
            if section is None:continue
            for loop in section.discrete:ax.plot(loop[:,1],loop[:,0],color=colors[r['group']] if not r['label'].endswith('_guard') else '#c18e46',lw=1.4)
        ax.axhline(110,color='#8b9297',ls=':',lw=.8);ax.axhline(122,color='#8b9297',ls=':',lw=.8)
        ax.set_xlim(-140,140);ax.set_ylim(85,127);ax.set_aspect('equal');ax.set_title(title+f' / Z={height:g}');ax.set_xlabel('Y / mm');ax.set_ylabel('X / mm');ax.grid(alpha=.15)
    fig.suptitle('右側の実STL断面：側板 X110〜122、追加フレーム X102〜110',fontsize=13)
    fig.tight_layout();fig.savefig(images/'inner_side_extensions.png',dpi=150);plt.close(fig)
    print('Wrote assembly STL, canonical view, 3 previews, comparison and mesh sections')


if __name__=='__main__':main()
