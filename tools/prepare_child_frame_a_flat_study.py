"""Prepare a uniform-thickness frame A study; never solve or optimise.

Reuse the canonical frame's 2D modules and confirmed interface coordinates.
All generated geometry is exploration-only under this part's analysis folder.
"""
from pathlib import Path
import argparse,hashlib,json,os,subprocess,sys
import numpy as np
import trimesh

ROOT=Path(__file__).resolve().parents[1]
PART=ROOT/'parts/child/exterior/printed/child_exterior_structural_frame'
CASE=PART/'_work/analysis/frame_a_flat_thickness'
OSC=r'C:\Program Files\OpenSCAD\openscad.com'

def save(p,v):
    p.parent.mkdir(parents=True,exist_ok=True)
    p.write_text(json.dumps(v,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--thickness',type=float,default=8)
    ap.add_argument('--reuse-rendered-inputs',action='store_true')
    args=ap.parse_args();t=args.thickness
    if not 6<=t<=12:raise ValueError('Preparation thickness must be between 6 and 12 mm')
    CASE.mkdir(parents=True,exist_ok=True)
    d=json.loads((PART/'spec/design_parameters.json').read_text(encoding='utf-8'))
    holes=d['clamp_holes_yz']+d['c_holes_yz']+d['joint_holes_yz']
    # Reuse the authored footprint, rim, seats and rounded access windows.
    # No old density surface, U walls or 45mm-deep stock is imported.
    scad='''// Exploration-only; generated by tools/prepare_child_frame_a_flat_study.py.
// Uniform local Z thickness; local X/Y = vehicle Y/Z.
use <../../../child_exterior_structural_frame.scad>
use <../../../../../../../../scad/lib/util.scad>
model="view";
flat_thickness=THICKNESS;
hole_d=HOLE_D; edge_chamfer=CHAMFER;
all_holes=HOLES;
$fn=48; eps=0.02;
module flat_hole_cuts() {
 for(p=all_holes) {
  translate([p[0],p[1],-eps]) hole(hole_d,flat_thickness+2*eps,fn=32,through=false);
  for(z=[0,flat_thickness-edge_chamfer]) translate([p[0],p[1],z])
   cylinder(d1=hole_d+(z==0?2*edge_chamfer:0),d2=hole_d+(z==0?0:2*edge_chamfer),h=edge_chamfer+eps);
 }
 clamp_eye_clearance();
}
module flat_domain() {
 difference() { edge_extrude(flat_thickness) profile("domain"); flat_hole_cuts(); }
}
module flat_preserve() {
 difference() {
  intersection() { edge_extrude(flat_thickness) stock_profile(); flat_domain(); }
  flat_hole_cuts();
 }
}
module flat_obstacle() {
 // Obstacles stay inside the same thickness so they do not expand the grid.
 union() { linear_extrude(flat_thickness) access_profile(); flat_hole_cuts(); }
}
if(model=="domain") flat_domain();
else if(model=="preserve") flat_preserve();
else if(model=="obstacle"||model=="cuts") flat_obstacle();
else if(model=="free") difference() { flat_domain(); flat_preserve(); }
else if(model=="view") {
 color([0.70,0.75,0.80,0.32]) flat_domain();
 color([0.18,0.67,0.43]) flat_preserve();
}
else assert(false,"Unknown preparation body");
'''
    for k,v in [('THICKNESS',t),('HOLE_D',d['m3_clearance']),('CHAMFER',d['edge_chamfer']),('HOLES',holes)]:scad=scad.replace(k,json.dumps(v))
    source=CASE/'frame_a_flat_preparation.scad'
    if args.reuse_rendered_inputs and (not source.exists() or source.read_text(encoding='utf-8')!=scad):
        raise RuntimeError('Cached geometry does not match this preparation')
    source.write_text(scad,encoding='utf-8')
    # Render domain/free/obstacle directly. Compose the many preserved islands
    # with Manifold after rendering the stock to avoid expensive CGAL unions.
    stock_scad=CASE/'frame_a_flat_stock.scad'
    stock_scad.write_text(f'use <../../../child_exterior_structural_frame.scad>\nedge_extrude({t}) stock_profile();\n',encoding='utf-8')
    for name,s,args_extra in [('domain',source,['-D','model="domain"']),('obstacle',source,['-D','model="obstacle"']),('stock',stock_scad,[])]:
        if args.reuse_rendered_inputs:
            if not (CASE/(name+'.stl')).exists():raise RuntimeError('Cached input is missing')
            continue
        with (CASE/(name+'_render.log')).open('w',encoding='utf-8') as log:
            subprocess.run([OSC,'--export-format','binstl','-o',str(CASE/(name+'.stl'))]+args_extra+[str(s)],stdout=log,stderr=subprocess.STDOUT,check=True)
    from clean_stl_degenerates import precision_weld,clean
    for n in ['domain','obstacle']:
        target=CASE/(n+'.stl')
        precision_weld(target,CASE/(n+'_precision_weld.json'),allow_collinear=True)
        clean(target,CASE/(n+'_edge_flip.json'),binary=True)
    domain=trimesh.load(CASE/'domain.stl',force='mesh');stock=trimesh.load(CASE/'stock.stl',force='mesh')
    preserve=trimesh.boolean.intersection([domain,stock],engine='manifold')
    # Native setup constructs its own free-cell mask. An exact CAD subtraction
    # can have touching voids at tangent seat boundaries; it is not a solver
    # input and is unnecessary for this preparation.
    for n,m in [('preserve',preserve)]:
        target=CASE/(n+'.stl');m.export(target)
        precision_weld(target,CASE/(n+'_precision_weld.json'),allow_collinear=True)
        clean(target,CASE/(n+'_edge_flip.json'),binary=True)
    rows={}
    for n in ['domain','preserve','obstacle']:
        m=trimesh.load(CASE/(n+'.stl'),force='mesh')
        rows[n]=dict(sha256=sha(CASE/(n+'.stl')),watertight=bool(m.is_watertight),winding_consistent=bool(m.is_winding_consistent),volume_mm3=float(m.volume),extents_mm=m.extents.tolist())
        if not m.is_watertight or not m.is_winding_consistent:raise RuntimeError(f'Invalid {n} input')
    if domain.extents[2]>t+.001:raise RuntimeError('Preparation is not a uniform-thickness plate')
    pts=np.array([[x,y,z] for x in np.linspace(-135,135,17) for y in np.linspace(-82,18,9) for z in [.1,t/2,t-.1]])
    if domain.contains(pts).any():raise RuntimeError('Lower access was filled')
    # The inner face and hole axes stay fixed; every outer washer face becomes t.
    regions={'handle':dict(type='box',min=[-40,256,0],max=[40,275,t]),
             'feet':dict(type='box',min=[-168,d['bottom'],0],max=[168,d['bottom']+4,t]),
             'foot_pin_left':dict(type='box',min=[-145,d['bottom'],0],max=[-135,d['bottom']+4,t]),
             'foot_pin_right':dict(type='box',min=[135,d['bottom'],0],max=[145,d['bottom']+4,t])}
    clamp_names=[];c_names=[]
    for prefix,points,names in [('clamp',d['clamp_holes_yz'],clamp_names),('c',d['c_holes_yz'],c_names)]:
        for i,(x,y) in enumerate(points):
            n=f'{prefix}_hole_{i}';regions[n]=dict(type='cylinder',axis='Z',centre=[x,y,0],r=4.5,range=[0,t]);names.append(n)
    def dist(names,v,f):return [dict(region=n,force=[float(x*f/len(names)) for x in v]) for n in names]
    def payload(v,f):return dist(clamp_names,v,.6*f)+dist(c_names,v,.4*f)
    def fixed(names):return [dict(region=n,fix='xyz') for n in names]
    floor=[dict(region='feet',fix='y',contact='ground'),dict(region='foot_pin_left',fix='xz',contact='ground'),dict(region='foot_pin_right',fix='z',contact='ground')]
    def lc(name,supports,loads,g=1):return dict(name=name,load_class='normal',supports=supports,loads=loads,gravity=dict(direction=[0,-1,0],g_factor=g))
    total=10*9.80665
    cases=[lc('carry_two_handles_2g',fixed(['handle']),payload([0,-1,0],total),2),
           lc('stand_two_frames_1g',floor,payload([0,-1,0],total/2)),
           lc('stand_one_frame_full_payload_1g',floor,payload([0,-1,0],total)),
           lc('handling_lateral_positive_2g',fixed(['handle']),payload([0,-.5,1],total)),
           lc('handling_lateral_negative_2g',fixed(['handle']),payload([0,-.5,-1],total)),
           lc('c_payload_from_suspended_clamps',fixed(clamp_names),dist(c_names,[0,-1,0],total*.4)),
           lc('c_fore_aft_positive_guard_load',fixed(clamp_names),dist(c_names,[1,0,0],30)+dist(c_names,[0,-1,0],total*.4)),
           lc('c_fore_aft_negative_guard_load',fixed(clamp_names),dist(c_names,[-1,0,0],30)+dist(c_names,[0,-1,0],total*.4))]
    study=dict(units='mm_N_MPa',material='BAMBU-PETG-BASIC',build_axis='Z',raster_axis='X',ground_axis='Y',infill=1.,walls=8,
      printer=dict(name='Virtual whole-A analysis envelope; physical X1C four-tile split',build_volume_mm=[450,450,20]),
      safety_factor=3,max_deflection_mm=2,voxel_mm=1,
      geometry=dict(design_space='domain.stl',preserve={'interfaces':dict(stl='preserve.stl',attach=[dict(type='all')])},obstacle={'functional_voids':'obstacle.stl'},clearance_mm=0),
      regions=regions,cases=cases,required_cases=[c['name'] for c in cases],
      design=dict(volfrac=.24,filter_mm=6,overhang=True,symmetry=[],optimizer='mma',stress=dict(safety_factor=3,p_norm=8,relax_q=.5,samples='all')),
      finish=dict(voxel_mm=1,smooth_mm=1,add={'interfaces':'preserve.stl'},cut={'functional_voids':'obstacle.stl'}),
      _status='exploration_only; preparation only; no FEA or optimisation performed',
      _what=f'Uniform {t:g}mm frame A plate, no U-section walls or 45mm stock.',
      _loads='10kg provisional upper bound at attachment interfaces, 60/40 clamp/C split. Native frame gravity is additional, deliberately conservative relative to the old total-vehicle10kg proxy.',
      _standing='Normal ground DOF Y only plus minimum X/Z pins to remove rigid-body modes. Ground is bilateral: uplift, sliding and complete-vehicle tipping remain unqualified.',
      _split='X0/Y80 four tiles planned; bolt-splice and screw lengths must be redesigned for the new thickness. The old M3x50 assembly/3MF belongs to the45mm prototype.',
      _physical_printer=dict(name='X1 Carbon',conservative_build_mm=[250,250,250],planned_tile_bounds_mm=[[170,212,t],[170,196,t]],note='The computational envelope is not a printer claim; all finished tiles and joints require actual fit checks.'),
      _verification_plan='After optimisation: finished-body mesh convergence and independent CCX including standing buckling; physical split-joint contact and complete-vehicle tipping are separate checks.',
      _interfaces='Same inner face and M3 hole coordinates; every outer washer seat at local Z=thickness. C upper outer seat changes from45mm to this plate thickness; no existing C part is changed.',
      _material_card=str(ROOT/'parts/child/exterior/printed/child_wte4_suspension_clamp/spec/bambu_petg_basic_material.json'))
    save(CASE/'frame_a_flat_study.json',study)
    save(CASE/'preparation_checks.json',dict(status='exploration_only',plate_thickness_mm=t,geometry=rows,lower_hand_clear=True,
      canonical_scad_sha256=sha(PART/'child_exterior_structural_frame.scad'),canonical_parameters_sha256=sha(PART/'spec/design_parameters.json'),case_count=len(cases),analysis_performed=False,optimisation_performed=False))
    print('Prepared uniform',t,'mm plate and',len(cases),'load cases; no solve',flush=True)
    env=os.environ.copy();env['PYTHONIOENCODING']='utf-8'
    with (CASE/'native_setup.log').open('w',encoding='utf-8') as log:
        result=subprocess.run([sys.executable,str(ROOT/'tools/clamp_bambu_material.py'),'setup',str(CASE/'frame_a_flat_study.json'),'--out',str(CASE/'native_setup'),'--voxel','1','--no-estimate'],env=env,stdout=log,stderr=subprocess.STDOUT)
    save(CASE/'native_setup_status.json',dict(exit_code=result.returncode,no_estimate=True,analysis_performed=False,optimisation_performed=False))
    print('Native setup exit',result.returncode,flush=True)
    if result.returncode!=0:raise RuntimeError('Native preparation checks failed; read native_setup.log')

if __name__=='__main__':main()
