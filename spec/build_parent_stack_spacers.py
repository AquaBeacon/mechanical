"""Canonical printed stack columns and breakaway print runner, mm.

Individual assembly shapes stay separate; the runner is an extra print part.
Existing GNSS columns are reused from their original STEP, never redefined.
"""
import FreeCAD as A, Part, MeshPart
from pathlib import Path
import sys, json, hashlib
R=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(R/'scad/lib'));import parent_gnss as G
P=R/'parts/common/interior/printed/stack_spacers';P.mkdir(parents=True,exist_ok=True)
O=R/'assemblies/parent_hand_service'
v=A.Vector
def save(stem,s):
 s=s.removeSplitter();assert s.isValid() and len(s.Solids)==1,(stem,len(s.Solids))
 s.exportStep(str(P/(stem+'.step')))
 mesh=MeshPart.meshFromShape(Shape=s,LinearDeflection=.025,AngularDeflection=.1,Relative=False)
 mesh.write(str(P/(stem+'.stl')))
 points,faces=mesh.Topology
 (P/(stem+'.scad')).write_text('// Generated by spec/build_parent_stack_spacers.py; no separate geometry.\npolyhedron(points='+json.dumps([[p.x,p.y,p.z] for p in points])+',faces='+json.dumps([list(f) for f in faces])+',convexity=10);\n',encoding='utf-8')
 print(stem,round(s.Volume,2),flush=True)
for stem,(diam,key) in ({} if '--set-only' in sys.argv else G.SONY_COLUMN_VARIANTS).items():
 h=G.SONY_COLUMN_LENGTH;r=diam/2;c=.15
 s=Part.makeCone(r-c,r,c,v(0,0,0)).fuse(Part.makeCylinder(r,h-2*c,v(0,0,c))).fuse(Part.makeCone(r,r-c,c,v(0,0,h-c)))
 kh=G.SONY_COLUMN_KEY_HEIGHT
 s=s.fuse(Part.makeCylinder(key/2,kh-.1,v(0,0,h))).fuse(Part.makeCone(key/2,key/2-.1,.1,v(0,0,h+kh-.1)))
 bore=Part.makeCylinder(3.45/2,h+kh+.2,v(0,0,-.1)).fuse(Part.makeCone(3.45/2+.15,3.45/2,.15,v(0,0,0))).fuse(Part.makeCone(3.45/2,3.45/2+.15,.15,v(0,0,h+kh-.15)))
 save(stem,s.cut(bore))
if '--columns-only' in sys.argv:sys.exit(0)
if '--set-only' in sys.argv:
 # Runner-only revisions keep the already verified body STEP/SCAD unchanged.
 for stem,(diam,key) in G.SONY_COLUMN_VARIANTS.items():
  s=Part.read(str(P/(stem+'.step')));b=s.optimalBoundingBox(False,False)
  assert abs(b.XLength-diam)<.001 and abs(b.ZLength-G.SONY_COLUMN_LENGTH-G.SONY_COLUMN_KEY_HEIGHT)<.001
  MeshPart.meshFromShape(Shape=s,LinearDeflection=.025,AngularDeflection=.1,Relative=False).write(str(P/(stem+'.stl')))
d=json.loads((O/'placement.json').read_text(encoding='utf-8'))
items=[it for it in d['items'] if it.get('print_set')=='parent_stack_spacer_set']
assert len(items)==12 and len({it['label'] for it in items})==12
# One flat runner with short 1.2 x 0.4 mm necks (two 0.2 mm layers).
# Attach on the non-bearing side; every column's own flat base sits on Z0.
runner=Part.makeBox(16*(len(items)-1)+12,2,1,v(0,0,0));members=[]
for i,it in enumerate(items):
 src=R/it['part']/(it['file']+'.step');s=Part.read(str(src))
 rotations=json.loads((src.parent/'manufacturing.json').read_text(encoding='utf-8')).get('print_rotations_deg',{}).get(it['file'],[0,0,0])
 for axis,angle in zip([v(1,0,0),v(0,1,0),v(0,0,1)],rotations):s.rotate(v(0,0,0),axis,angle)
 b=s.optimalBoundingBox(False,False)
 row=0;x=6+16*i;y=12
 shift=[x-(b.XMin+b.XMax)/2,y-(b.YMin+b.YMax)/2,-b.ZMin]
 s.translate(v(*shift))
 low=s.common(Part.makeBox(240,140,.35,v(-10,-10,.025))).optimalBoundingBox(False,False)
 x=(low.XMin+low.XMax)/2;near=low.YMin
 # The branch ends 1 mm before the part; the neck overlaps its side by .3.
 branch=Part.makeBox(1.4,near-(60*row+3),1,v(x-.7,60*row+2,0))
 neck=Part.makeBox(1.2,1.3,.4,v(x-.6,near-1,0))
 runner=runner.fuse(branch).fuse(neck).fuse(s)
 members.append(dict(label=it['label'],part=it['part'],file=it['file'],translation_mm=shift,rotations_deg=rotations,source_step_sha256=hashlib.sha256(src.read_bytes()).hexdigest(),neck_width_mm=1.2,neck_height_mm=.4,neck_length_mm=1,neck_xy_mm=[x,near-.5]))
save('parent_stack_spacer_set',runner)
(P/'set_members.json').write_text(json.dumps(dict(set_file='parent_stack_spacer_set',quantity=1,members=members,breakaway_note='Cut side neck flush. Keep both bearing faces, locator and bore intact. Runner is discarded; never assembled.'),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
refs=['spec/build_parent_stack_spacers.py','scad/lib/parent_gnss.py','assemblies/parent_hand_service/placement.json','spec/build_parent_gnss.py','scad/lib/parent_corner_mounts.py',P.relative_to(R).as_posix()+'/set_members.json']+list(dict.fromkeys(it['part']+'/'+it['file']+'.step' for it in items if it['part']!=P.relative_to(R).as_posix()))
import os
(P/'manufacturing.json').write_text(json.dumps(dict(source_dependencies=[os.path.relpath(R/q,P).replace('\\','/') for q in refs],print_rotations_deg={},release_status='fit_check_prototype',portable_stl_export_format='stl_ascii',structural_print_conditions=dict(material='PETG',layer_height_mm=.2,walls=4,infill_percent=100),permitted_sharp_edges='Flat bearing/key interfaces and deliberately sharp sacrificial necks; handling/bore edges have 0.1–0.15 mm chamfers.'),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

# JSON/SCAD dependencies precede a real final STL rebuild.
MeshPart.meshFromShape(Shape=Part.read(str(P/"parent_stack_spacer_set.step")),LinearDeflection=.025,AngularDeflection=.1,Relative=False).write(str(P/"parent_stack_spacer_set.stl"))
