"""Publish reviewed native outputs and configure the existing parent assembly.

Requires successful geometry, fastening and service reports. Does not rebuild
or alter the existing floor, LiPo parts or original variants.
"""
from pathlib import Path
import argparse,copy,hashlib,json,shutil,sys
import trimesh

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'scad/lib'))
from parent_gnss import SONY_BOARD_LIFT
ASM=ROOT/'assemblies/parent_hand_service'
WORK=ASM/'_work/analysis/retrofit_20261024'

def read(p):return json.loads(Path(p).read_text(encoding='utf-8-sig'))
def write(p,d):Path(p).write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
def digest(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def logged(run,prefix):
    return json.loads(next(s[len(prefix):] for s in (run/'logs/freecad.log').read_text(encoding='utf-8',errors='replace').splitlines() if s.startswith(prefix)))

def main():
    ap=argparse.ArgumentParser()
    for key in ['parts','layout','fasteners','service']:ap.add_argument('--'+key,required=True,type=Path)
    args=ap.parse_args();runs={k:getattr(args,k).resolve() for k in ['parts','layout','fasteners','service']}
    for run in runs.values():assert read(run/'report.json')['status']=='passed',run
    layout=logged(runs['layout'],'LAYOUT_SURVEY=')
    fast=logged(runs['fasteners'],'FASTENER_REPORT=')
    service=logged(runs['service'],'SERVICE_REPORT=')
    assert all(c['volume_mm3']<.001 for c in layout['checks'])
    assert all(n['geometry_pass'] for n in fast['nuts'])
    assert len(fast['direct_pcb'])==8 and all(n['passes'] for n in fast['direct_pcb'])
    assert all(n['passes'] for n in fast['thread_lengths'])
    assert len(fast['spacer_threads'])==27 and all(n['passes'] for n in fast['spacer_threads'])
    assert all(n['passes'] for n in fast['opposed_screws'])
    assert len(fast['adapter_clamps'])==4 and all(n['passes'] for n in fast['adapter_clamps'])
    assert all(n['washer_floor_probe_mm3']>.1 and n['washer_case_overlap_mm3']<.001 and n['head_case_overlap_mm3']<.001 for n in fast['floor_bearings'])
    assert all(n['continuous_envelope_pass'] for n in service['motion']) and not any(n['hits'] for n in service['tools'])
    # Each check must refer to the current shared geometry, never an earlier candidate.
    for run in runs.values():
        job=read(run/'job.json')
        for rel in ['scad/lib/parent_service_retrofit.py','scad/lib/parent_corner_mounts.py','scad/lib/parent_gnss.py']:
            assert job['snapshots'][rel]['sha256']==digest(ROOT/rel),(run,rel)
    baseline=read(WORK/'source_hashes.json')
    for rel,sha in baseline.items():
        if 'floor_plate.' in rel:assert digest(ROOT/rel)==sha,rel
    meta=logged(runs['parts'],'RETROFIT_METADATA=')
    report=read(runs['parts']/'report.json')
    # The report structure is inspected before publication; actual exports are
    # verified from the fresh run, including closed meshes and source snapshots.
    exported={}
    for name,folder in meta['folders'].items():
        dst=ROOT/folder;dst.mkdir(parents=True,exist_ok=True)
        for suffix in ['step','stl']:
            source=runs['parts']/(name+'.'+suffix);assert source.is_file()
            shutil.copy2(source,dst/source.name)
        mesh=trimesh.load_mesh(dst/(name+'.stl'));assert mesh.is_watertight and mesh.is_winding_consistent and mesh.volume>0
        scad='// Generated by spec/build_parent_hand_service.py --service-retrofit; edit scad/lib/parent_service_retrofit.py.\n'
        scad+='polyhedron(points='+json.dumps(mesh.vertices.tolist())+',faces='+json.dumps(mesh.faces[:,::-1].tolist())+',convexity=10);\n'
        (dst/(name+'.scad')).write_text(scad,encoding='utf-8')
        exported[name]=dict(folder=folder,step_sha256=digest(dst/(name+'.step')),stl_sha256=digest(dst/(name+'.stl')))
    # Publish STL bytes after all generated SCAD siblings. copy2 would retain
    # export timestamps older than these views and incorrectly signal stale CAD.
    for name, folder in meta['folders'].items():
        shutil.copyfile(runs['parts']/(name+'.stl'), ROOT/folder/(name+'.stl'))
    for folder in sorted(set(meta['folders'].values())):
        if '/printed/' not in folder:continue
        p=ROOT/folder/'manufacturing.json';d=read(p) if p.exists() else {}
        deps=d.setdefault('source_dependencies',[])
        import os
        for rel in ['spec/build_parent_hand_service.py','scad/lib/parent_service_retrofit.py','scad/lib/parent_corner_mounts.py','parts/parent/interior/printed/ann_mb1_internal_rack/ann_mb1_coax_ring.step']:
            entry=os.path.relpath(ROOT/rel,ROOT/folder).replace('\\','/')
            if entry not in deps:deps.append(entry)
        rotations=d.setdefault('print_rotations_deg',{})
        for name,f in meta['folders'].items():
            if f==folder:rotations[name]=[180,0,0] if name=='antenna_service_shelf' else [90,0,0] if name=='cradle_nut_keeper' else [0,0,0]
        d['release_status']='fit_check_prototype';write(p,d)
    path=ASM/'placement.json';old=read(path)
    backup=WORK/'placement_before_retrofit.json'
    if not backup.exists():write(backup,old)
    d=copy.deepcopy(read(backup))
    remove_prefixes=('main_column_','sony_column_','gnss_column_','main_mount_','pwr_mount_','main_carrier_','sony_carrier_','gnss_frame_','antenna_rack_','ground_plate_mount_','ground_plate_nut_','antenna_mount_','antenna_nut_')
    remove={'main_mount_plate','antenna_rack','gnss_coax_route','sony_mount_plate'}
    d['items']=[it for it in d['items'] if it['label'] not in remove and not it['label'].startswith(remove_prefixes)]
    sensor_names={'gnss_receiver','gnss_sma_plug','gnss_pin_headers','gnss_universal_pcb','gnss_xh_keepout','gnss_universal_carrier','magnetometer'}
    for it in d['items']:
        n=it['label']
        if n=='spresense' or (n.startswith('sony_mount_') and n!='sony_mount_plate'):
            it['ops'].insert(0,{'translate':[0,0,SONY_BOARD_LIFT]})
        if n=='p_main':it['ops'].insert(0,{'translate':[0,0,3]})
        if n=='p_pwr':it['ops']=[{'translate':[0,-11,5.5]}]+it['ops']
        if n in sensor_names or n.startswith(('mag_bolt_','mag_nut_','gnss_pcb_')):it['ops'].insert(0,{'translate':[0,0,16]})
        if n in {'antenna_ground_plate','gnss_antenna'}:it['ops'].insert(0,{'translate':[0,-12,8.8]})
        if n.startswith('gnss_pcb_bolt_'):it['file']='screw_m3x12'
        if n in {'plate','lipo_tray','lipo_ret_lid','sony_mount_plate','gnss_universal_carrier'}:
            it['print']=False;it['note']='Reuse existing printed part unchanged; no reprint for this retrofit.'
        if n=='sony_mount_plate':
            it['print']=True;it['note']='Reprint 3.2 mm plate; PCB and seats raised 1.6 mm, existing column joint retained.'
        if n=='coax_ring':
            it['file']='ann_mb1_coax_ring_service';it['print']=True
            it['note']='Reprint with open-top lead entry; original footprint, case-tool paths and floor holes retained.'
    for name,folder in meta['folders'].items():
        if name=='ann_mb1_coax_ring_service':continue
        if name=='cradle_nut_keeper':
            for i,xyz in enumerate(meta['keeper_instances']):d['items'].append(dict(label=name+'_'+str(i),part=folder,file=name,group='interior',color='DarkOrange',ops=[{'translate':xyz}],print=True))
            continue
        d['items'].append(dict(label=name,part=folder,file=name,group='interior',color='DarkOrange' if '/printed/' in folder else 'DimGray',ops=[],print='/printed/' in folder))
    for row in meta['fasteners']:
        x,y=row['xy'];diam=row['diameter'];label=row['label'];direction=row['direction']
        stem='screw_m%d x%d'%(diam,row['length']);stem=stem.replace(' ','')
        if diam==4:stem+='_socket'
        ops=[{'translate':[x,y,row['head_z']]}]
        if direction>0:ops.append({'rotate':[180,0,0]})
        assert (ROOT/'parts/common/interior/cots/screw'/(stem+'.step')).exists(),stem
        d['items'].append(dict(label='retrofit_'+label+'_bolt',part='parts/common/interior/cots/screw',file=stem,group='interior',color='Silver',ops=ops))
        if row['nut_z'] is not None:
            d['items'].append(dict(label='retrofit_'+label+'_nut',part='parts/common/interior/cots/screw',file='screw_nut_m'+str(diam),group='interior',color='Silver',ops=[{'translate':[x,y,row['nut_z']]},{'rotate':[0,0,30]}]))
        if row['washer']:
            d['items'].append(dict(label='retrofit_'+label+'_washer',part='parts/common/interior/cots/screw',file='screw_washer_m3_05',group='interior',color='Silver',ops=[{'translate':[x,y,8.34]}]))
    d.pop('spacer_delivery',None)
    for stale in ['service_only','lift_mm','moving_labels','service_translation_mm','access_revision','gnss_design','magnetometer_design']:
        d.pop(stale,None)
    d['note']='2026-10-24 retrofit: floor and LiPo fixtures reused; MAIN/antenna module removed with four M3x8 screws; fixed feet stay on floor.'
    d['coordinate_system']='mm; floor18.8, MAIN45, PWR33.8, GNSS72, Sony67.2, antenna top95.9, lid roof97.1.'
    d['retrofit']=dict(status='fit_check_prototype',floor_reprint=False,floor_machining=False,maximum_new_screw_length_mm=30,
                       spacer_fastening='Plain 2.8mm axial pilots; no internal nuts or nut keepers; 27 plastic-thread joints',
                       pcb_fastening='MAIN M3x8 / PWR M3x6 directly into 2.8mm plastic pilots; eight nuts removed',
                       antenna_lift_mm=8.8,main_lift_mm=3,pwr_lift_mm=5.5,pwr_south_mm=11,pwr_rotation_deg=0,pico_height_above_board_mm=17,sensor_lift_mm=16,
                       service='Disconnect MAIN wiring and SMA; remove four M3x8 service bolts; free the antenna-side loop and lift module120mm. Tall walls stay on module; short feet stay floor-fixed.',
                       cable_motion='Stored R20 lead geometry checked; flexible cable deformation and physical winding remain unverified.')
    d['build_order']=[it['label'] for it in d['items']];write(path,d)
    service_d=copy.deepcopy(d);service_d['name']='parent_hand_service_open'
    moving={'main_service_frame','antenna_service_shelf','p_main','antenna_ground_plate','gnss_antenna'}
    for it in service_d['items']:
        if it['label'] in moving or it['label'].startswith(('retrofit_main_pcb_','retrofit_shelf_joint_','retrofit_steel_','retrofit_antenna_')):
            it['ops'].insert(0,{'translate':[0,0,120]})
    service_d['items']=[it for it in service_d['items'] if not (it['label'].startswith('retrofit_cradle_service_') and it['label'].endswith('_bolt')) and it['label'] not in {'coax_service_loop','coax_receiver_service','gnss_sma_plug','lid_keepout'}]
    service_d['build_order']=[it['label'] for it in service_d['items']]
    service_d['note']='Service review pose only: wiring disconnected; flexible cable is omitted rather than represented by an invalid rigid translation.'
    write(ASM/'service_placement.json',service_d)
    config=read(ASM/'print_config.json');backup=WORK/'print_config_before_retrofit.json'
    if not backup.exists():write(backup,config)
    config.pop('spacer_delivery',None);config['status']='fit_check_prototype'
    config['note']='16種類16個。スペーサ・床側受け・MAIN枠の内部ナット穴を廃止。抜け止め4個は不要。MAINはM3×8、電源基板はM3×6を各4本、内接径2.8 mmの樹脂下穴へ直接固定。基板用ナット8個は不要。最下段・LiPo固定具は再使用、穴加工なし。整備用4本も樹脂下穴へ直接締結。手順は ../retrofit_report.md。実物嵌合・ねじ保持力・寿命は未確認。'
    config['modifiers']=[m for m in config.get('modifiers',[]) if m.get('host')!='battery_base']
    config['notes']=list(dict.fromkeys(config.get('notes',[])+['assemblies/parent_hand_service/retrofit_report.md','docs/配線・ケーブル計画.md','assemblies/parent_hand_service/sony_plate_thickening_report.md']))
    write(ASM/'print_config.json',config)
    write(WORK/'release_record.json',dict(status='fit_check_prototype',runs={k:str(v) for k,v in runs.items()},exports=exported,fasteners=meta['fasteners'],floor_hashes={k:v for k,v in baseline.items() if 'floor_plate.' in k}))
    for key,data in [('layout_survey',layout),('fastener_survey',fast),('service_survey',service)]:write(WORK/(key+'.json'),data)
    print('Published geometry and placement; run assembly build, print sync and checks next.')

if __name__=='__main__':main()
