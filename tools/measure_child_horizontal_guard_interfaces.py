"""Extract the confirmed WTE4 tab profile; run in FreeCAD CLI.

Generated SCAD is an interface derivative of the existing vendor STEP,
not a second definition of the purchased part.
"""
from pathlib import Path
import hashlib,json
import FreeCAD as App
import Part

root=Path(__file__).resolve().parents[1]
source=root/'parts/child/exterior/cots/wte4_end_cap_5xm10/WTE4-M-END-CAP-5XM10-R2.step'
cap=Part.read(str(source))
wire=max(cap.slice(App.Vector(0,0,1),8),key=lambda w:Part.Face(w).Area)
bound=wire.BoundBox
cx=(bound.XMin+bound.XMax)/2;cy=(bound.YMin+bound.YMax)/2
points=[[round(v.x-cx,6),round(v.y-cy,6)] for v in wire.discretize(Deflection=.025)]
if points[0]==points[-1]:points.pop()
planes=sorted(set(round(f.CenterOfMass.z,6) for f in cap.Faces if f.BoundBox.ZLength<1e-5))
assert abs(cx-60.15)<1e-5 and abs(cy-57.15)<1e-5 and 4.0 in planes
assert cap.isValid() and abs(cap.BoundBox.ZLength-10)<1e-5
sha=hashlib.sha256(source.read_bytes()).hexdigest()
target=root/'scad/lib/wte4_endcap_key_profile.scad'
target.write_text('// Generated by tools/measure_child_horizontal_guard_interfaces.py; do not edit.\n'
    '// Existing vendor STEP SHA-256: '+sha+'\n'
    'wte4_key_profile_points='+json.dumps(points,separators=(',',':'))+';\n'
    f'wte4_endcap_total_t={cap.BoundBox.ZLength:.6f};\nwte4_key_half_width={bound.XLength/2:.6f};\nwte4_key_base_r={bound.YLength/2:.6f};\n'
    'wte4_endcap_plug_t=4;\nwte4_endcap_exposed_t=wte4_endcap_total_t-wte4_endcap_plug_t;\n'
    'module wte4_key_profile() { polygon(wte4_key_profile_points); }\n',encoding='utf-8')
out=root/'assemblies/child_horizontal_plate_frame/_work/analysis/guards'
out.mkdir(parents=True,exist_ok=True)
report=dict(source=source.relative_to(root).as_posix(),sha256=sha,section_z_mm=8,
    centre_mm=[cx,cy],extents_mm=[bound.XLength,bound.YLength],points=len(points),
    planar_z_mm=planes,tab_symmetry_deg=180,profile_tessellation_deflection_mm=.025,
    choice='Existing confirmed 2026-09-27 cap tabs; no use of old hinged guard geometry')
for label,radius,count in [('cap_screws_xz_mm',1.6,6),('penetrators_xz_mm',5.1,5)]:
    axes=sorted(set((round(f.Surface.Center.x-cx,6),round(f.Surface.Center.y-cy,6))
        for f in cap.Faces if hasattr(f.Surface,'Radius') and hasattr(f.Surface,'Axis')
        and abs(f.Surface.Radius-radius)<1e-5 and abs(f.Surface.Axis.z)>.99))
    assert len(axes)==count,(label,axes)
    report[label]=axes
(out/'vendor_profile.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
print('GUARD_PROFILE_EXTRACTED',len(points),flush=True)
